-- 020_import_sources.sql
--
-- Откъде е дошла една оферта. Досега всичко беше „някой потребител я е качил“.
-- Сега можем да внасяме реални касови бонове (напр. събрани от кошчетата до
-- касите) или цени от официални брошури — и това ТРЯБВА да се вижда, за да
-- няма съмнение, че данните са измислени.
--
-- Прозрачността е и правната защита: читателят вижда източника на всяка цена.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. Източник на публикацията
-- ---------------------------------------------------------------------------
alter table posts add column if not exists source text not null default 'user';
alter table posts add column if not exists source_note text;

comment on column posts.source is
  'user | receipt_basket (бон от кошчето на касата) | brochure (официална брошура) | tiktok_signal (сигнал от TikTok, с разрешение) | import';
comment on column posts.source_note is
  'Свободен текст към източника: напр. „Кошче на касата, Lidl Габрово, 12 броя“ или линк към брошурата.';

-- Полезен индекс: „покажи ми всичко от кошчето на касата“.
create index if not exists posts_source_idx on posts (source) where source <> 'user';

-- ---------------------------------------------------------------------------
-- 2. Официален (редакционен) профил
--
-- Внасяните бонове не са „потребителски отзиви“ — качени са от редакцията.
-- Затова имат собствен профил, който се вижда като такъв. Никакви измислени
-- хора: фалшивите потребителски отзиви са забранени (Омнибус директивата).
-- ---------------------------------------------------------------------------
alter table profiles add column if not exists is_official boolean not null default false;

create index if not exists profiles_official_idx on profiles (is_official) where is_official;

-- 019_founder_bonus.sql
--
-- Значка „Основател“ — за първите хора, които напълнят базата, докато е още
-- празна. Проблемът: нов сайт с празни списъци не убеждава никого да качи
-- първата си находка („празен ресторант“). Затова първата находка, качена до
-- няколко минути след регистрацията, се награждава веднага — значка + точки.
--
-- Значката НЕ е по показател (metric = null): не се отключва от syncBadges(),
-- а само от кода при създаване на първата публикация. Така никой не може да
-- я вземе със задна дата или със 100-тна публикация.
--
-- Настройките се управляват от админ панела (секция „Бонус за основатели“),
-- за да може да се спре, щом базата се напълни.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. Значката
-- ---------------------------------------------------------------------------
insert into badges (id, title, icon, description, color, sort_order, metric, threshold)
values (
  'badge-founder',
  'Основател',
  'sparkles',
  'Качи първата си находка до няколко минути след регистрацията',
  '#F59E0B',
  5,
  null,
  1
)
on conflict (id) do update
  set title       = excluded.title,
      icon        = excluded.icon,
      description = excluded.description,
      color       = excluded.color,
      sort_order  = excluded.sort_order,
      metric      = excluded.metric,
      threshold   = excluded.threshold;

-- ---------------------------------------------------------------------------
-- 2. Настройки (не се презаписват, ако вече съществуват)
-- ---------------------------------------------------------------------------
insert into app_settings (key, value) values
  ('founder_bonus',      'on'),
  ('founder_window_min', '5'),
  ('founder_points',     '100')
on conflict (key) do nothing;

-- ---------------------------------------------------------------------------
-- 3. Всеки съществуващ профил получава реда (заключен, unlocked_at = null),
--    за да се вижда значката в профила със „Заключена“ / „0 / 1“.
-- ---------------------------------------------------------------------------
insert into profile_badges (profile_id, badge_id)
select p.id, 'badge-founder' from profiles p
on conflict (profile_id, badge_id) do nothing;

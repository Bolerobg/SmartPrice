-- 022_assistant_knowledge.sql
--
-- „Ценко“ трябва да е професионален работник на приложението: да знае всяка
-- функция, всеки бутон и всяко правило — и да го обяснява с прости стъпки,
-- като на 10-годишно дете.
--
-- Проблемът: приложението се променя. Днес има радар, утре — нова функция.
-- Ако знанието е „зашито“ в кода, всеки път ще трябва програмист.
--
-- Затова знанието живее в БАЗАТА:
--   • admin панелът пише тук нови теми (или редактира старите);
--   • Ценко чете таблицата при всеки въпрос и вкарва подходящите теми
--     в отговора си.
-- Така „щом влезе ново нещо в базата, Ценко вече го знае“ — без нов билд.
-- ============================================================================

create table if not exists assistant_knowledge (
  id          bigserial primary key,
  -- Кратко заглавие на темата, напр. „Как се качва находка?“
  title       text not null check (char_length(btrim(title)) between 3 and 200),
  -- Тялото на знанието: стъпки, правила, числа. Пише се на прост език.
  body        text not null check (char_length(btrim(body)) between 3 and 4000),
  -- По кои думи трябва да се „задейства“ тази тема (за търсене).
  keywords    text[] not null default '{}',
  -- Група за подредба в панела: basics | points | receipts | raffles | safety | news
  category    text not null default 'basics',
  -- Колко е важна: 1 = винаги се дава на модела, 10 = само при съвпадение.
  priority    integer not null default 5 check (priority between 1 and 10),
  is_active   boolean not null default true,
  -- 'seed' = дошло от миграцията; 'admin' = написано от човек в панела.
  source      text not null default 'admin',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

comment on table assistant_knowledge is
  'Знанието на AI съветника „Ценко“. Пише се от админ панела — така новите функции се обясняват без нов билд.';
comment on column assistant_knowledge.priority is
  '1 = винаги се включва в контекста на модела (основни неща), 10 = само ако думите съвпадат.';

create index if not exists assistant_knowledge_active_idx
  on assistant_knowledge (is_active, priority);

-- Търсене по ключови думи (за кирилица ползваме прост GIN по масива).
create index if not exists assistant_knowledge_keywords_idx
  on assistant_knowledge using gin (keywords);


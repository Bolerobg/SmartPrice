-- ============================================================================
-- 018 — Настройки на приложението + реалистичен демо играч
--
-- Защо: демо играчът трябва да изглежда като истински човек (име, град, снимка),
-- за да може да се види как ще изглежда победа на реален участник — преди
-- пускане и за снимки.
--
-- ВАЖНО: „истински“ важи само в ДЕМО РЕЖИМ, който е изрично обявен и се вижда
-- в панела с червена лента. В реален режим демо играч не може да участва —
-- иначе реалните хора виждат измислен победител и това е подвеждане.
-- ============================================================================

create table if not exists app_settings (
  key        text primary key,
  value      text not null,
  updated_at timestamptz not null default now()
);

comment on table app_settings is 'Настройки на приложението (ключ/стойност). Не са тайни — не слагай пароли тук.';

insert into app_settings (key, value) values
  ('demo_mode', 'off')
on conflict (key) do nothing;

comment on column app_settings.value is 'Стойност като текст: on/off, число или кратък текст.';

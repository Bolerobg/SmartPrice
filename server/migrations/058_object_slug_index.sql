-- 058: ⚡ ИНДЕКС за „slug“ на обект — спира 500-ите и бавното отваряне.
--
-- Проблемът (диагностициран на живо, 23.10.2026):
--   Страницата на обект търси rows по
--     md5(lower(btrim(coalesce(place_name,'')) || '|' || lower(btrim(coalesce(city,''))))) = $1
--   Такъв индекс НЯМАШЕ → Postgres сканираше ВСИЧКИ ~121 000 публикувани поста
--   при ВСЯКО отваряне на обект (заявката вървеше ~2-6 секунди).
--
--   При натоварване (един човек отваря приложението = 6-10 заявки наведнъж)
--   тези заявки задръстваха пула към базата и след 10 секунди чакане падаха с
--   грешка „timeout exceeded when trying to connect“ → потребителят виждаше 500
--   и екранът оставаше празен (без значка, без статистики).
--
-- Решението: съставен (functional) индекс точно върху този израз, само за
-- публикуваните редове. Само се ДОБАВЯ индекс — нищо не се трие и не се променя.
-- Същият списък с обекти отваря и страницата на обект и „Радара“, затова
-- индексът помага навсякъде.
--
-- ⚠️ Изразът тук ТРЯБВА да е символ по символ същият като в
--    server/src/lib/objects.ts (coalesce → btrim → lower → md5), иначе
--    Postgres няма да го използва и файда няма.

create index if not exists posts_venue_slug_idx
  on posts (
    md5(
      lower(btrim(coalesce(place_name, '')) || '|' || lower(btrim(coalesce(city, ''))))
    )
  )
  where status = 'published';

-- Същият slug се брои и когато търсим обект по име+град (Radar / търсене).
create index if not exists posts_place_name_fold_idx
  on posts (lower(btrim(coalesce(place_name, ''))))
  where status = 'published';

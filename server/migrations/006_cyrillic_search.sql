-- ============================================================================
-- 006 — Търсене, което работи с КИРИЛИЦА
--
-- Откритият проблем: базата е създадена с C колация. При нея PostgreSQL
-- lower() НЕ сгъва кирилица — lower('София') остава 'София'.
-- Затова търсене с малки букви не намираше градове и имена:
--
--   select count(*) from posts where city ilike '%софия%';  ->  0
--   (а в таблицата съществува ред с city = 'София')
--
-- Заглавията се намираха само защото в демо данните думите вече бяха
-- с малки букви. Градове, имена на обекти и търговци не се намираха.
--
-- Решение: собствена функция, която сгъва кирилицата ръчно. lower() се
-- грижи за латиницата, translate() — за кирилицата.
-- ============================================================================

create or replace function sp_fold(t text)
returns text
language sql
immutable
as $$
  select translate(
    lower(coalesce(t, '')),
    -- главни кирилски (вкл. Ѝ — „и с гравис“, използва се за късия член)
    'АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЬЮЯЍ',
    -- съответните малки
    'абвгдежзийклмнопрстуфхцчшщъьюяѝ'
  );
$$;

comment on function sp_fold(text) is
  'Сгъва регистъра и на латиница, и на кирилица. Нужна е, защото базата е с '
  'C колация и вградената lower() не пипа кирилица. Ползва се при търсенето.';

-- Индекси за по-бързо търсене по най-често търсените полета
create index if not exists posts_title_fold_idx
  on posts (sp_fold(title));

create index if not exists posts_place_fold_idx
  on posts (sp_fold(place_name));

create index if not exists posts_city_fold_idx
  on posts (sp_fold(city));
/**
 * Прави ли се офертата от КАТАЛОГ на верига (Метро, Кауфланд…)?
 *
 * Защо е нужно: при каталожните цени пише „ЦЕНА В ВЕРИГАТА“, а при находките
 * от хора — „ПЛАТЕНА ЦЕНА“. Разликата е важна за доверието: в едното има
 * снимка на етикета от човек, в другото е обявена цена от брошура.
 */
export function isCatalogOffer(source?: string | null): boolean {
  return String(source || '').toLowerCase() === 'scraper';
}
